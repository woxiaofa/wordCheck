/**
 * 小程序文本口令（#小程序://）—— 复制到微信聊天会变成可点链接。
 *
 * 关键事实（2026-10-19 实测，推翻了 10-13 的假设）：
 *   手拼的 `#小程序://功课抽查/` **点了永远「链接无效」**，因为斜杠后面是空的，
 *   缺微信签发的短链 token。10-13 我们以为是「没上线」，上线后仍然无效才查实。
 *   正确取法：手机打开**已发布**的小程序 → 右上角 … → 复制链接，
 *   得到形如 `#小程序://功课抽查/dBP41ypt6JND5Li` 的真口令，把尾部随机码填到下面。
 *
 * 为什么要放进 shared/：这个口令同时被三处复制文案与云端「催一催」用到，
 * 放在一处，换口令只改一行（跑 shared:sync + functions:prepare 自动铺到两端）。
 *
 * 注意：口令像门牌号，不是参数通道 —— 带不了邀请码 sid，对方进来落在首页。
 */
var OPEN_LINK = '#小程序://功课抽查/dBP41ypt6JND5Li';

module.exports = {
  OPEN_LINK: OPEN_LINK,
  /** 复制文案里的最后一句：点开链接后要做什么，讲清楚转化率才高 */
  openLine: function (what) {
    return '点这里直接打开小程序 👉 ' + OPEN_LINK + (what ? '，' + what : '');
  }
};
